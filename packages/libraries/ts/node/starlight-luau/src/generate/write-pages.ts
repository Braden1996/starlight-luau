import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

import type { GeneratedPage } from "./generate-api.ts";

export const MARKER_FILE = ".starlight-luau";

export class UnsafeOutputError extends Error {
  constructor(directory: string) {
    super(
      `${directory} already has content that starlight-luau did not write. Choose an empty \`output\` folder, or delete this one.`,
    );
    this.name = "UnsafeOutputError";
  }
}

function assertSafeToReplace(directory: string): void {
  if (!existsSync(directory) || existsSync(join(directory, MARKER_FILE))) {
    return;
  }
  if (readdirSync(directory).length > 0) {
    throw new UnsafeOutputError(directory);
  }
}

export function writePages(directory: string, pages: readonly GeneratedPage[]): void {
  assertSafeToReplace(directory);
  rmSync(directory, { recursive: true, force: true });
  mkdirSync(directory, { recursive: true });
  writeFileSync(
    join(directory, MARKER_FILE),
    "Generated by starlight-luau. Everything in this folder is replaced on each build.\n",
  );
  for (const page of pages) {
    const path = join(directory, page.path);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, page.content);
  }
}
